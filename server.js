/* =========================================
   長高祭2026
   混雑情報共有API
========================================= */

const express = require("express");
const cors = require("cors");

const app = express();


/* =========================================
   基本設定
========================================= */

const PORT = process.env.PORT || 3000;


/* =========================================
   ミドルウェア
========================================= */

/*
  Vercelなど別のサイトから
  このRender APIへアクセスできるようにする
*/

app.use(cors());


/*
  JSON形式のデータを受け取れるようにする
*/

app.use(express.json());


/* =========================================
   混雑情報データ
========================================= */

/*
  データの形式

  {
    "modal1": {
      status: "empty",
      updatedAt: "2026-09-07T..."
    }
  }

  企画IDをキーとして保存する
*/

const crowdData = {};


/* =========================================
   GET
   現在の全混雑情報を取得
========================================= */

app.get(
  "/api/crowd",
  (req, res) => {

    res.status(200).json(
      crowdData
    );

  }
);


/* =========================================
   POST
   混雑状況を更新
========================================= */

app.post(
  "/api/crowd",
  (req, res) => {

    const {
      id,
      status
    } = req.body;


    /* =====================================
       ID確認
    ===================================== */

    if(
      !id ||
      typeof id !== "string"
    ){

      return res.status(400).json({
        error:
          "企画IDが正しくありません"
      });

    }


    /* =====================================
       状態確認
    ===================================== */

    const allowedStatuses = [
      "empty",
      "normal",
      "crowded"
    ];


    if(
      !allowedStatuses.includes(
        status
      )
    ){

      return res.status(400).json({
        error:
          "混雑状況が正しくありません"
      });

    }


    /* =====================================
       更新日時
    ===================================== */

    const updatedAt =
      new Date().toISOString();


    /* =====================================
       データ保存
    ===================================== */

    crowdData[id] = {
      status:
        status,

      updatedAt:
        updatedAt
    };


    /* =====================================
       更新結果を返す
    ===================================== */

    res.status(200).json({

      id:
        id,

      status:
        status,

      updatedAt:
        updatedAt

    });

  }
);


/* =========================================
   動作確認用
========================================= */

app.get(
  "/",
  (req, res) => {

    res.status(200).json({
      message:
        "長高祭2026 混雑情報APIは正常に動作しています"
    });

  }
);


/* =========================================
   ヘルスチェック
========================================= */

app.get(
  "/health",
  (req, res) => {

    res.status(200).json({
      status:
        "ok"
    });

  }
);


/* =========================================
   404
========================================= */

app.use(
  (req, res) => {

    res.status(404).json({
      error:
        "ページが見つかりません"
    });

  }
);


/* =========================================
   サーバー起動
========================================= */

app.listen(
  PORT,
  "0.0.0.0",
  () => {

    console.log(
      `Server is running on port ${PORT}`
    );

  }
);
