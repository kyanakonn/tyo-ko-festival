const express = require("express");
const cors = require("cors");

const app = express();

/* =========================================
   Renderのポート設定
========================================= */

const PORT = process.env.PORT || 3000;


/* =========================================
   ミドルウェア
========================================= */

app.use(cors());

app.use(
  express.json({
    limit: "1mb"
  })
);


/* =========================================
   混雑状況データ
========================================= */

/*
  データ形式

  {
    "企画ID": {
      status: "empty",
      updatedAt: "2026-09-07T..."
    }
  }
*/

const crowdData = {};


/* =========================================
   サーバー確認用
========================================= */

app.get(
  "/",
  (req, res) => {

    res.json({
      message: "長高祭2026 混雑状況共有APIは正常に動作しています"
    });

  }
);


/* =========================================
   混雑状況を取得
   GET /api/crowd
========================================= */

app.get(
  "/api/crowd",
  (req, res) => {

    res.status(200).json(
      crowdData
    );

  }
);


/* =========================================
   混雑状況を更新
   POST /api/crowd
========================================= */

app.post(
  "/api/crowd",
  (req, res) => {

    const id =
      req.body?.id;

    const status =
      req.body?.status;


    /* -----------------------------------------
       ID確認
    ----------------------------------------- */

    if(
      !id ||
      typeof id !== "string"
    ){

      return res.status(400).json({
        error: "企画IDが正しくありません"
      });

    }


    /* -----------------------------------------
       混雑状況確認
    ----------------------------------------- */

    const allowedStatuses = [
      "empty",
      "normal",
      "crowded"
    ];


    if(
      !allowedStatuses.includes(
        status
      )
    ){

      return res.status(400).json({
        error: "混雑状況が正しくありません"
      });

    }


    /* -----------------------------------------
       更新時刻
    ----------------------------------------- */

    const updatedAt =
      new Date().toISOString();


    /* -----------------------------------------
       データ保存
    ----------------------------------------- */

    crowdData[id] = {

      status:
        status,

      updatedAt:
        updatedAt

    };


    /* -----------------------------------------
       crowd.htmlへ返す
    ----------------------------------------- */

    return res.status(200).json({

      id:
        id,

      status:
        status,

      updatedAt:
        updatedAt

    });

  }
);


/* =========================================
   404
========================================= */

app.use(
  (req, res) => {

    res.status(404).json({
      error: "ページが見つかりません"
    });

  }
);


/* =========================================
   エラー処理
========================================= */

app.use(
  (error, req, res, next) => {

    console.error(
      "サーバーエラー:",
      error
    );

    res.status(500).json({
      error: "サーバーでエラーが発生しました"
    });

  }
);


/* =========================================
   サーバー起動
========================================= */

app.listen(
  PORT,
  () => {

    console.log(
      `Server is running on port ${PORT}`
    );

  }
);
